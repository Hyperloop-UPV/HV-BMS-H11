void BCC_MCU_WaitSec(uint16_t delay) {
    uint32_t total = delay * 1000;
    uint32_t i = 0;
    for (; i < total; i += UINT16_MAX) {
        BCC_MCU_WaitMs(i);
    }
    BCC_MCU_WaitMs(i - total);
}

void BCC_MCU_WaitMs(uint16_t delay) { BCC_MCU_WaitUs((uint32_t)delay * 1000UL); }

void BCC_MCU_WaitUs(uint32_t delay) {
    // 6-cycle loop with dual-issue capability
    uint32_t count = delay * 48 * 4;  // Approximately 400/6 ≈ 67

    __asm volatile(
        "1:                     \n"
        "subs   %0, %0, #1      \n"
        "nop                    \n"
        "nop                    \n"
        "nop                    \n"
        "nop                    \n"
        "bne    1b              \n"
        : "+r"(count)
        :
        : "cc");
}

